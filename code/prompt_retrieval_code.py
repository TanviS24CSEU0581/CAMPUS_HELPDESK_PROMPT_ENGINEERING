import glob
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

ids = []
txt = []
for line in open("policy.txt", encoding="utf-8").read().splitlines():
    if " | " in line:
        a, b = line.split(" | ", 1)
        if "-" in a and " " not in a:
            ids.append(a.strip())
            txt.append(b.strip())
print("policy sections found:", len(ids))

qs = pd.read_csv("questions.csv")
print("questions found:", len(qs))
print("columns:", list(qs.columns))

vec = TfidfVectorizer(stop_words="english").fit(txt)
mat = vec.transform(txt)
ctxs = []
for q in qs["QUESTION"]:
    sc = cosine_similarity(vec.transform([str(q)]), mat)[0]
    top = sc.argsort()[::-1][:3]
    ctxs.append("\n".join("[" + ids[i] + "] " + txt[i] for i in top))
qs["Retrieved"] = ctxs

for f in sorted(glob.glob("v*.txt")):
    tmpl = open(f, encoding="utf-8").read()
    out = qs.copy()
    out["Prompt"] = [tmpl.replace("{ctx}", c).replace("{q}", str(q)) for c, q in zip(ctxs, qs["QUESTION"])]
    out.to_csv("ready_" + f.replace(".txt", ".csv"), index=False)
    print("made ready_" + f.replace(".txt", ".csv"))

print("-----")
print(out["Prompt"][0])

